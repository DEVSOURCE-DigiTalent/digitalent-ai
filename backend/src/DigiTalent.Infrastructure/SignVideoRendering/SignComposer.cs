using System.Globalization;
using DigiTalent.Domain.Constants;

namespace DigiTalent.Infrastructure.SignVideoRendering;

/// <summary>
/// The last FFmpeg command of both renderers: the signer track (clips joined, or the 3D avatar track) with the lesson
/// video. OVERLAY = the signer in a window at the bottom left (by default; height ~½ of the video so hands and face
/// stay readable, a thin light border) over the lesson video with its sound — the 3D avatar has no window: its track is
/// transparent and the avatar stands flush in the bottom corner (<see cref="AvatarWindowFor"/>); FULLSCREEN = the signer
/// alone, full frame, with the lesson sound; TRACK_ONLY = the signer track alone (no sound). The output keeps the lesson
/// video's frame grid; H.264 + AAC MP4 with faststart. Arguments only (no shell), file names generated by the renderers.
/// </summary>
public static class SignComposer
{
    /// <summary>Light border around the signer window, in pixels (separates it from the lesson picture).</summary>
    public const int BorderPx = 2;

    /// <summary>
    /// Width / height of the transparent avatar's place: square, so an arm stretched out toward the middle of the video
    /// is not cut in mid-air (the room is invisible, it costs nothing).
    /// </summary>
    public const double AvatarAspect = 1.0;

    /// <summary>
    /// Largest frame of H.264 level 3.1 (the level every browser encoder accepts), in 16 × 16 macroblocks: the transparent
    /// tile's frame is twice as wide (colour | alpha), a larger place is rendered smaller and upscaled.
    /// </summary>
    public const int MaxAvatarFrameMacroblocks = 3600;

    /// <summary>Where the signer window goes on the lesson video.</summary>
    public sealed record Window(int Width, int Height, int X, int Y);

    public static Window WindowFor(SignVideoSettings settings, int videoWidth, int videoHeight)
    {
        var s = settings;
        var (width, height) = Fit(s, videoWidth, videoHeight, s.WindowHeightPercent, (double)s.SignWidth / s.SignHeight);
        var margin = (int)Math.Round(Math.Min(videoWidth, videoHeight) * s.MarginPercent / 100.0);
        var x = s.WindowSide == "RIGHT" ? videoWidth - width - margin : margin;
        var y = videoHeight - height - margin;
        // Even positions: the colour planes of yuv420p are half size, an odd edge would blur the border's colour.
        return new Window(width, height, Math.Max(0, x - x % 2), Math.Max(0, y - y % 2));
    }

    /// <summary>
    /// OVERLAY with the 3D avatar: the place of its transparent tile — <see cref="SignVideoSettings.AvatarWindowHeightPercent"/>
    /// of the video high, flush with the bottom edge (the avatar is cut at the hips by it, like a presenter) and with the
    /// side edge, no margin and no border. The browser frames the avatar inside it toward that side.
    /// </summary>
    public static Window AvatarWindowFor(SignVideoSettings settings, int videoWidth, int videoHeight)
    {
        var s = settings;
        var (width, height) = Fit(s, videoWidth, videoHeight, s.AvatarWindowHeightPercent, AvatarAspect);
        var x = s.WindowSide == "RIGHT" ? videoWidth - width : 0;
        var y = videoHeight - height;
        return new Window(width, height, Math.Max(0, x - x % 2), Math.Max(0, y - y % 2));
    }

    /// <summary>Size the browser renders the transparent avatar at: its place on the video, smaller only when the doubled frame would pass <see cref="MaxAvatarFrameMacroblocks"/>.</summary>
    public static (int Width, int Height) AvatarTile(SignVideoSettings settings, int videoWidth, int videoHeight)
    {
        var window = AvatarWindowFor(settings, Math.Max(2, videoWidth - videoWidth % 2), Math.Max(2, videoHeight - videoHeight % 2));
        static bool Fits(int w, int h) => (2 * w + 15) / 16 * ((h + 15) / 16) <= MaxAvatarFrameMacroblocks;
        if (Fits(window.Width, window.Height)) return (window.Width, window.Height);

        var scale = Math.Sqrt(MaxAvatarFrameMacroblocks * 256.0 / (2.0 * window.Width * window.Height));
        var width = (int)(window.Width * scale);
        width -= width % 2;
        int Height(int w) { var h = (int)Math.Round(w * (double)window.Height / window.Width); return h - h % 2; }
        while (width > 64 && !Fits(width, Height(width))) width -= 2;
        return (width, Height(width));
    }

    /// <summary>Window of the given aspect, <paramref name="heightPercent"/> of the video high and never wider than allowed; even sizes.</summary>
    private static (int Width, int Height) Fit(SignVideoSettings s, int videoWidth, int videoHeight, double heightPercent, double aspect)
    {
        var height = (int)Math.Round(videoHeight * heightPercent / 100.0);
        var width = (int)Math.Round(height * aspect);
        var maxWidth = (int)Math.Round(videoWidth * s.WindowWidthPercent / 100.0);
        if (width > maxWidth)
        {
            width = maxWidth;
            height = (int)Math.Round(width / aspect);
        }

        return (Math.Max(64, width - width % 2), Math.Max(64, height - height % 2));
    }

    /// <param name="signerInput">FFmpeg options and "-i file" of the signer track (input 1, or 0 for TRACK_ONLY).</param>
    /// <param name="signerPrep">Filters applied to the signer first, ending with a comma (e.g. "tpad=…,"), or "".</param>
    /// <param name="transparentSigner">
    /// OVERLAY only: the signer track is the transparent avatar (colour premultiplied on black | alpha as grey, side by side).
    /// </param>
    public static List<string> Arguments(
        SignVideoSettings s,
        string mode,
        string source,
        IReadOnlyList<string> signerInput,
        string signerPrep,
        MediaInfo sourceInfo,
        string output,
        bool transparentSigner = false)
    {
        var width = Math.Max(2, sourceInfo.Width - sourceInfo.Width % 2);
        var height = Math.Max(2, sourceInfo.Height - sourceInfo.Height % 2);
        var duration = new[] { "-t", Seconds(sourceInfo.DurationMs) };
        var finish = new[] { "-movflags", "+faststart", "-progress", "pipe:1", "-nostats", output };
        var audio = new[] { "-map", "0:a?", "-c:a", "aac", "-b:a", "128k" };
        var color = s.FfmpegColor;

        switch (mode)
        {
            case SignVideo.RenderMode.TrackOnly:
                return Command(signerInput, new[] { "-an", "-vf", $"{signerPrep}setsar=1,format=yuv420p" }, Encoder(s), duration, finish);

            case SignVideo.RenderMode.Fullscreen:
            {
                var filter = string.Create(CultureInfo.InvariantCulture,
                    $"[1:v]{signerPrep}scale={width}:{height}:force_original_aspect_ratio=decrease,pad={width}:{height}:(ow-iw)/2:(oh-ih)/2:color={color},setsar=1,format=yuv420p[v]");
                return Command(new[] { "-i", source }, signerInput, new[] { "-filter_complex", filter, "-map", "[v]" }, audio, Encoder(s), duration, finish);
            }

            case var _ when transparentSigner: // OVERLAY (and any other mode) with the transparent avatar
            {
                var place = AvatarWindowFor(s, width, height);
                return Command(new[] { "-i", source }, signerInput, new[] { "-filter_complex", TransparentOverlay(signerPrep, width, height, place), "-map", "[v]" }, audio, Encoder(s), duration, finish);
            }

            default:
            {
                var window = WindowFor(s, width, height);
                var inner = (W: window.Width - 2 * BorderPx, H: window.Height - 2 * BorderPx);
                var filter = string.Create(CultureInfo.InvariantCulture,
                    $"[0:v]scale={width}:{height},setsar=1[base];" +
                    $"[1:v]{signerPrep}scale={inner.W}:{inner.H},pad={window.Width}:{window.Height}:{BorderPx}:{BorderPx}:color=0xF8FAFC,setsar=1[sign];" +
                    $"[base][sign]overlay=x={window.X}:y={window.Y}:eof_action=pass,format=yuv420p[v]");
                return Command(new[] { "-i", source }, signerInput, new[] { "-filter_complex", filter, "-map", "[v]" }, audio, Encoder(s), duration, finish);
            }
        }
    }

    /// <summary>
    /// The transparent avatar over the lesson video. The track is split again: the right half (alpha as grey) becomes the
    /// alpha, with a small dead zone so compression noise neither tints the lesson nor eats the avatar; the left half
    /// (colour premultiplied on black) is divided by that alpha (lut2, so it works on every FFmpeg version — the
    /// unpremultiply filter of recent versions only acts on frames flagged premultiplied); then a plain overlay. The
    /// alpha branch stays RGB: a grey branch would be range-converted (tv/pc) by FFmpeg's format negotiation.
    /// </summary>
    private static string TransparentOverlay(string signerPrep, int width, int height, Window place)
    {
        const string deadZone = "clip((val-10)*255/235,0,255)";
        const string unpremultiply = "if(y,min(255,x*255/y),0)";
        return string.Create(CultureInfo.InvariantCulture,
            $"[0:v]scale={width}:{height},setsar=1[base];" +
            $"[1:v]{signerPrep}scale={2 * place.Width}:{place.Height},format=yuv420p,split[col][mat];" +
            $"[mat]crop=iw/2:ih:iw/2:0,format=gbrp,lut=c0='{deadZone}':c1='{deadZone}':c2='{deadZone}',split[am][ac];" +
            $"[am]extractplanes=g[alpha];" +
            $"[col]crop=iw/2:ih:0:0,format=gbrp[pm];" +
            $"[pm][ac]lut2=c0='{unpremultiply}':c1='{unpremultiply}':c2='{unpremultiply}'[straight];" +
            $"[straight][alpha]alphamerge,format=yuva420p,setsar=1[sign];" +
            $"[base][sign]overlay=x={place.X}:y={place.Y}:eof_action=pass,format=yuv420p[v]");
    }

    public static IEnumerable<string> Encoder(SignVideoSettings s) => new[]
    {
        "-c:v", "libx264", "-preset", s.Preset, "-crf", s.Crf.ToString(CultureInfo.InvariantCulture), "-pix_fmt", "yuv420p",
    };

    public static List<string> Command(params IEnumerable<string>[] parts)
    {
        var arguments = new List<string> { "-nostdin", "-hide_banner", "-loglevel", "error", "-y" };
        foreach (var part in parts) arguments.AddRange(part);
        return arguments;
    }

    public static string Seconds(int ms) => (ms / 1000.0).ToString("0.###", CultureInfo.InvariantCulture);

    /// <summary>"8,5" — seconds for the Vietnamese progress text.</summary>
    public static string Vi(int ms) => (ms / 1000.0).ToString("0.#", CultureInfo.InvariantCulture).Replace('.', ',');

    /// <summary>"out_time_us=1234" / "out_time_ms=1234" (both microseconds) of FFmpeg's -progress output.</summary>
    public static long? ProgressMicroseconds(string line)
    {
        foreach (var prefix in new[] { "out_time_us=", "out_time_ms=" })
        {
            if (line.StartsWith(prefix, StringComparison.Ordinal) && long.TryParse(line.AsSpan(prefix.Length), NumberStyles.Integer, CultureInfo.InvariantCulture, out var value))
            {
                return value;
            }
        }

        return null;
    }
}
